func TestPointwiseBO(t *testing.T) {
	want := []float64{0, 0.9205213785171509, 0.7408284544944763, 0.22600145637989044, 0.0374436229467392}
	got := optimizers.PointwiseBO("text", "changkun", "testsession", "2", 4)
	if len(want) != len(got) {
		t.Fatalf("incorrect inference length: got %v, want %v", len(got), len(want))
	}
	for i := range want {
		elem := want[i]
		got := got[i]
		if math.Abs(elem-got) < 1e-7 {
			continue
		}
		log.Fatalf("elements are inequal: want %v, got %v", elem, got)
	}
}

func TestPairwiseBO(t *testing.T) {
	want := [][]float64{
		{0.09473322331905365, 0.23589693009853363, 0.4161151945590973, 0.20954696834087372, 0.21740086376667023},
		{0.28325510025024414, 0.9296807646751404, 0.07407829165458679, 0.9857743382453918, 0.13594233989715576},
	}
	got := optimizers.PairwiseBO("text", "changkun", "testsession", "3", 4)
	if len(want) != len(got) {
		t.Fatalf("incorrect inference length: got %v, want %v", len(got), len(want))
	}

	for i := range want {
		wantP := want[i]
		gotP := got[i]

		for j := range wantP {
			if math.Abs(wantP[j]-gotP[j]) < 1e-3 { // Note: pairwise BO seems a bit less accurate.
				continue
			}
			log.Fatalf("elements are inequal: want %v, got %v", wantP[j], gotP[j])
		}
	}
}
